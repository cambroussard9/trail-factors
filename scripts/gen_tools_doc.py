"""Generate docs/tools.md from the MCP server's own tool definitions.

    uv run python scripts/gen_tools_doc.py            # write docs/tools.md
    uv run python scripts/gen_tools_doc.py --check    # exit 1 if it is stale

The page is built from exactly what an MCP client receives: each tool's name,
description and input schema, as `list_tools()` returns them. Nothing is
written by hand, so the page cannot describe a tool the server does not have.
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import sys
import textwrap

from trail_factors import mcp_server as M
from trail_factors.paths import REPO_ROOT

OUT = REPO_ROOT / "docs" / "tools.md"


def _tools() -> list:
    listed = M.mcp.list_tools()
    tools = asyncio.run(listed) if inspect.isawaitable(listed) else listed
    return sorted(tools, key=lambda t: t.name)


def _param_rows(schema: dict) -> list[str]:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    rows = []
    for name, spec in props.items():
        kind = spec.get("type")
        if kind is None and "anyOf" in spec:
            kind = " | ".join(s.get("type", "?") for s in spec["anyOf"])
        default = "required" if name in required else repr(spec.get("default"))
        rows.append(f"| `{name}` | {kind or '?'} | {default} |")
    return rows


def render() -> str:
    tools = _tools()
    out = [
        "# MCP tools",
        "",
        "<!-- GENERATED by scripts/gen_tools_doc.py from the server's tool",
        "     definitions. Do not edit by hand; re-run the script. -->",
        "",
        f"The `trail-factors` MCP server (stdio) exposes {len(tools)} tools. "
        "Every result is a JSON envelope with an `outcome` "
        "(`result`, `rejected`, `absent`, `refused` or `broken`), a payload, "
        "a remedy, `retryable`, and the corpus fingerprint and calc_version.",
        "",
        "| Tool | Summary |",
        "|---|---|",
    ]
    for t in tools:
        first = (t.description or "").strip().split("\n\n")[0]
        first = " ".join(first.split())
        out.append(f"| [`{t.name}`](#{t.name}) | {first} |")
    for t in tools:
        out += ["", f"## {t.name}", ""]
        out.append(textwrap.dedent(t.description or "(no description)").strip())
        rows = _param_rows(t.input_schema or {})
        out += ["", "**Parameters**", ""]
        if rows:
            out += ["| Name | Type | Default |", "|---|---|---|", *rows]
        else:
            out.append("None.")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docs/tools.md differs from the server",
    )
    a = ap.parse_args()
    text = render()
    if a.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("docs/tools.md is stale: run scripts/gen_tools_doc.py")
            sys.exit(1)
        print(f"docs/tools.md is current ({text.count(chr(10) + '## ')} tools)")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote docs/tools.md ({text.count(chr(10) + '## ')} tools)")


if __name__ == "__main__":
    main()
